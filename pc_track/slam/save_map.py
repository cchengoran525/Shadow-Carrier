#!/usr/bin/env python3
"""save_map.py —— /map(OccupancyGrid) → PGM+YAML，零依赖版 map_saver

为什么不用 nav2_map_server 的 map_saver_cli：本科研轨 PC 上未装（且装它需要 sudo）；
PGM/YAML 是 ROS 地图的标准交换格式，30 行自己写比引入依赖干净。语义对齐 nav2
map_saver：occupied_thresh=0.65 / free_thresh=0.25，PGM 0=占据 / 254=自由 / 205=未知。

用法:
  python3 save_map.py [输出前缀]        # 默认 map_<时间戳>，产出 <前缀>.pgm + <前缀>.yaml
  等待 /map 一帧（默认最多 30s）后写出并退出。
"""
import os
import sys
import time

import rclpy
from rclpy.node import Node
from nav_msgs.msg import OccupancyGrid

OCC_TH = 0.65
FREE_TH = 0.25
OUT = sys.argv[1] if len(sys.argv) > 1 else f"map_{time.strftime('%m%d_%H%M%S')}"


def to_pgm_values(grid):
    vals = bytearray(len(grid))
    for i, p in enumerate(grid):
        if p < 0 or p > 100:
            vals[i] = 205                       # 未知
        elif p / 100.0 > OCC_TH:
            vals[i] = 0                          # 占据（黑）
        elif p / 100.0 < FREE_TH:
            vals[i] = 254                        # 自由（白）
        else:
            vals[i] = 205                        # 未定按未知画
    return vals


def main():
    rclpy.init()
    node = Node("save_map")
    got = []

    def cb(msg: OccupancyGrid):
        if not got:
            got.append(msg)

    node.create_subscription(OccupancyGrid, "/map", cb, 1)
    t0 = time.time()
    while rclpy.ok() and not got and time.time() - t0 < 30:
        rclpy.spin_once(node, timeout_sec=0.5)
    if not got:
        print("30s 内没收到 /map —— 建图节点还在跑吗？")
        sys.exit(1)
    m = got[0]
    h = m.info
    with open(f"{OUT}.pgm", "wb") as f:
        f.write(f"P5\n# Generated by pc_track/slam/save_map.py\n{h.width} {h.height}\n255\n".encode())
        f.write(to_pgm_values(m.data))
    with open(f"{OUT}.yaml", "w", encoding="utf-8") as f:
        o = h.origin
        f.write(f"image: {os.path.abspath(OUT)}.pgm\n"
                f"resolution: {h.resolution}\n"
                f"origin: [{o.position.x}, {o.position.y}, {o.position.z}]\n"
                f"negate: 0\noccupied_thresh: {OCC_TH}\nfree_thresh: {FREE_TH}\n")
    n_occ = sum(1 for p in m.data if 0 <= p <= 100 and p / 100.0 > OCC_TH)
    n_free = sum(1 for p in m.data if 0 <= p <= 100 and p / 100.0 < FREE_TH)
    print(f"地图已存: {OUT}.pgm/.yaml  {h.width}x{h.height} @ {h.resolution}m/格  "
          f"占据 {n_occ} / 自由 {n_free} 栅格")
    node.destroy_node()
    rclpy.shutdown()


if __name__ == "__main__":
    main()
